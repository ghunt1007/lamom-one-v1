// คำถามที่แสดงในแผง: เฉพาะหน้า (ถ้ามี) + 3 คำถามทั่วไป
export function pageAsksFor(path = '') {
  const p = String(path || '').split('?')[0].replace(/\/+$/, '') || '/'
  const own = PAGE_SPECIFIC[p]
  return own ? [{ key: 'page', ...own }, ...PAGE_ASKS] : PAGE_ASKS
}

