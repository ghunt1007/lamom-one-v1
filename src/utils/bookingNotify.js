// ข้อความแจ้งความคืบหน้าให้ลูกค้า (ส่งทาง LINE) เมื่อเปลี่ยนสถานะใบจอง — เซลส์อ่าน/แก้แล้วคัดลอกไปส่งเอง
// ลูกค้ามักโทรถามว่า "รถถึงไหนแล้ว" แจ้งก่อนทุกครั้งที่สถานะขยับช่วยลดสายถามและสร้างความประทับใจ
const fmtDate = s => {
  if (!/^\d{4}-\d{2}-\d{2}/.test(s || '')) return ''
  const [y, m, d] = s.slice(0, 10).split('-').map(Number)
  const TH = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.']
  return `${d} ${TH[m - 1]} ${y + 543}`
}

export function customerStatusMessage(b, status) {
  const first = String(b.custName || '').trim().split(/\s+/)[0]
  const hi = first ? `สวัสดีครับคุณ${first}` : 'สวัสดีครับ'
  const car = [b.brand && !String(b.model || '').toLowerCase().includes(String(b.brand).toLowerCase()) ? b.brand : '', b.model].filter(Boolean).join(' ') || 'รถ'
  const sales = b.salesName ? `\n${b.salesName} (เซลส์ผู้ดูแล)` : ''
  const when = fmtDate(b.deliveryDate)
  switch (status) {
    case 'รอผลไฟแนนซ์':
      return `${hi} ทางเราส่งเอกสารขอสินเชื่อ${car}ให้ไฟแนนซ์เรียบร้อยแล้วครับ ได้ผลเมื่อไหร่จะรีบแจ้งทันทีครับ${sales}`
    case 'รอรถ':
      return `${hi} ขอแสดงความยินดีครับ 🎉 ไฟแนนซ์อนุมัติเรียบร้อยแล้ว ตอนนี้อยู่ระหว่างรอรถ ${car} เข้าโชว์รูม รถมาถึงเมื่อไหร่จะรีบแจ้งนัดวันส่งมอบครับ${sales}`
    case 'รอส่งมอบ':
      return `${hi} ข่าวดีครับ รถ ${car} ของคุณมาถึงแล้ว ตอนนี้กำลังเตรียมรถให้พร้อมส่งมอบ${when ? ` นัดส่งมอบวันที่ ${when}` : ' สะดวกรับรถวันไหน แจ้งได้เลยครับ'}${sales}`
    case 'ตัดตัวเลขรอส่งมอบ':
      return `${hi} รถ ${car} ของคุณดำเนินการจดทะเบียนเรียบร้อย${when ? ` พร้อมส่งมอบวันที่ ${when}` : ' อีกนิดเดียวก็พร้อมส่งมอบแล้ว'} วันรับรถรบกวนนำบัตรประชาชนมาด้วยนะครับ${sales}`
    case 'ส่งมอบแล้ว':
      return `${hi} ขอบคุณที่ไว้วางใจเลือก ${car} กับเรานะครับ 🙏 ขับขี่ปลอดภัย มีอะไรสงสัยเรื่องการใช้งานหรือการชาร์จ ทักมาได้ตลอดครับ ถ้าประทับใจฝากรีวิวหรือแนะนำเพื่อนๆ ด้วยนะครับ${sales}`
    default:
      return ''
  }
}

// ข้อความทักลูกค้าที่เสียดีลไปแล้ว 30 วัน+ ตามเหตุผลเดิม (หัวข้อ "ลองติดต่อใหม่" ในงานของฉันวันนี้)
// reasonKey มาจาก classifyLostReason() — ไม่ใส่ราคา/โปรที่ไม่รู้จริง ชวนคุยกลับเฉยๆ
export function revisitMessage(c, reasonKey) {
  const first = String(c.firstName || c.name || '').trim().split(/\s+/)[0]
  const hi = first ? `สวัสดีครับคุณ${first}` : 'สวัสดีครับ'
  const car = c.interestedModel ? ` ${c.interestedModel}` : ''
  switch (reasonKey) {
    case 'finance':
      return `${hi} เงื่อนไขไฟแนนซ์แต่ละเจ้าปรับอยู่เรื่อยๆ ผมลองเช็กให้ใหม่ได้นะครับ เผื่อคราวนี้มีทางที่เหมาะกว่าเดิม สนใจให้ลองดูอีกครั้งไหมครับ`
    case 'price':
      return `${hi} ไม่ได้คุยกันนานเลย ผมขอเช็กราคาและข้อเสนอล่าสุดของรถ${car}ให้ดูอีกรอบได้ไหมครับ`
    case 'timing':
      return `${hi} ตอนนี้สะดวกคุยเรื่องรถ${car}หรือยังครับ ถ้าพร้อมเมื่อไหร่ ผมเตรียมรถให้ทดลองขับได้เลยครับ`
    case 'no_contact':
      return `${hi} ผมจากโชว์รูมที่คุณเคยสนใจรถ${car}ครับ ไม่แน่ใจว่ายังสนใจอยู่ไหม ถ้ามีคำถามอะไรทักมาได้เลยนะครับ`
    default:
      return `${hi} ผมจากโชว์รูมที่เคยคุยเรื่องรถ${car}ครับ ถ้ายังสนใจหรือมีคำถามอะไร ทักมาได้เลยนะครับ ยินดีช่วยเสมอครับ`
  }
}

// ขอบคุณหลังทดลองขับ (ส่ง LINE วันเดียวกัน) — ข้อความต่างกันตามผล: สนใจมาก/อาจจะ/ไม่สนใจ/จองแล้ว
export function testDriveThanks(t, result) {
  const first = String(t.customerName || '').trim().split(/\s+/)[0]
  const hi = first ? `สวัสดีครับคุณ${first}` : 'สวัสดีครับ'
  const car = String(t.model || '').trim() || 'รถ'
  const sales = t.staff ? `\n${t.staff} (เซลส์ผู้ดูแล)` : ''
  switch (result) {
    case 'booked':
      return `${hi} ขอบคุณที่มาทดลองขับและไว้วางใจจอง ${car} กับเรานะครับ 🙏 ขั้นตอนต่อไปผมจะแจ้งความคืบหน้าให้ทราบเป็นระยะ มีอะไรสงสัยทักมาได้ตลอดครับ${sales}`
    case 'interested':
      return `${hi} ขอบคุณที่มาทดลองขับ ${car} วันนี้นะครับ 🙏 ถ้าอยากให้ผมคำนวณค่างวด หรือเช็กสีและรถที่พร้อมส่งให้ แจ้งได้เลยครับ ผมจัดให้ทันที${sales}`
    case 'notinterested':
      return `${hi} ขอบคุณที่สละเวลามาทดลองขับ ${car} วันนี้นะครับ 🙏 ถ้าวันหลังอยากลองรุ่นอื่นหรือมีคำถามเรื่องรถไฟฟ้า ทักมาได้ตลอดครับ${sales}`
    default:
      return `${hi} ขอบคุณที่มาทดลองขับ ${car} วันนี้นะครับ 🙏 ขับแล้วรู้สึกยังไงบ้างครับ มีจุดไหนที่อยากรู้เพิ่ม เช่น ค่างวด การชาร์จ หรือระยะทางวิ่งจริง ถามผมได้เลยครับ${sales}`
  }
}

